#!/usr/bin/env bash
# Runs the CMS server locally against the Neon database in the cloud.
#
#   ./neon-local.sh                 # fetch secrets, then `go run ./cmd/server`
#   ./neon-local.sh make migrate    # fetch secrets, then run any other command
#   ./neon-local.sh --fetch-only    # just (re)write .env.neon
#   REFRESH=1 ./neon-local.sh       # re-download even if .env.neon exists
#
# Secrets come from Google Secret Manager (same ones Cloud Run uses, see
# deploy.sh) and are cached in server/.env.neon (git-ignored, mode 600).
# Environment variables override app.env, so the rest of your local settings
# (port, media dir, etc.) still apply.
#
# Requires: gcloud, logged in with access to the project
#   (gcloud auth login).
set -euo pipefail

PROJECT=${PROJECT:-web-azma}
cd "$(dirname "$0")"
ENV_FILE=.env.neon

# ENV_VAR=secret-name pairs to pull from Secret Manager.
SECRETS=(
  "DB_SOURCE=azma-db-source"
)

fetch() {
  command -v gcloud >/dev/null || { echo "gcloud not found on PATH" >&2; exit 1; }
  local tmp
  tmp=$(mktemp)
  chmod 600 "$tmp"
  trap 'rm -f "$tmp"' RETURN
  echo "# Generated by neon-local.sh from Secret Manager ($PROJECT). Do not commit." >"$tmp"
  for pair in "${SECRETS[@]}"; do
    local var=${pair%%=*} secret=${pair#*=} value
    echo "Fetching $secret -> $var" >&2
    value=$(gcloud secrets versions access latest --secret "$secret" --project "$PROJECT")
    # Quote for safe `source`-ing.
    printf '%s=%q\n' "$var" "$value" >>"$tmp"
  done
  mv "$tmp" "$ENV_FILE"
  echo "Wrote $(pwd)/$ENV_FILE" >&2
}

if [[ "${1:-}" == "--fetch-only" ]]; then
  fetch
  exit 0
fi

if [[ ! -s "$ENV_FILE" || -n "${REFRESH:-}" ]]; then
  fetch
fi

set -a
# shellcheck disable=SC1090
source "./$ENV_FILE"
set +a

export ENVIRONMENT=${ENVIRONMENT:-development}

if [[ $# -eq 0 ]]; then
  set -- go run ./cmd/server
fi
echo "Running against Neon: $*" >&2
exec "$@"
